import sqlite3,re,json
from pathlib import Path
w=Path('Proyecto/.documentacion');s=(w/'modelo_fn3.sql').read_text(encoding='utf-8');s=re.sub(r'CREATE SCHEMA[^;]+;|SET search_path[^;]+;','',s);s=s.replace(' GENERATED BY DEFAULT AS IDENTITY','')
c=sqlite3.connect(':memory:');c.execute('PRAGMA foreign_keys=ON');c.executescript(s)
ts=json.loads((w/'schema.json').read_text(encoding='utf-8'))
print('Tables',len(ts),'FK',sum(len(c.execute('PRAGMA foreign_key_list('+t['name']+')').fetchall()) for t in ts))
assert len(c.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall())==45
# The schema graph must cover every declared entity and FK.
for t in ts:
 assert len(c.execute('PRAGMA table_info('+t['name']+')').fetchall())==len(t['fields'])
for name in ['cuenta_conexion','factura_obligacion','resultado_importacion_factura']:
 assert any(t['name']==name for t in ts)
print('DDL portable structure: PASS; PostgreSQL cross-row triggers remain specified, not executed.')

