CREATE SCHEMA IF NOT EXISTS horizonte_fn3;

SET search_path TO horizonte_fn3;

CREATE TABLE empresa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nit VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(200) NOT NULL,
  umbral NUMERIC(18,2) NOT NULL,
  PRIMARY KEY (id),
  CHECK (umbral >= 0)
);

CREATE TABLE usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  username VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(128) NOT NULL,
  nombres VARCHAR(150) NOT NULL,
  apellidos VARCHAR(150) NOT NULL,
  email VARCHAR(254) NOT NULL,
  activo BOOLEAN NOT NULL,
  superusuario BOOLEAN NOT NULL,
  fecha_registro TIMESTAMPTZ NOT NULL,
  ultimo_acceso TIMESTAMPTZ,
  PRIMARY KEY (id)
);

CREATE TABLE rol (
  codigo VARCHAR(16) NOT NULL,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  PRIMARY KEY (codigo)
);

CREATE TABLE membresia (
  empresa_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  rol_codigo VARCHAR(16) NOT NULL,
  PRIMARY KEY (empresa_id, usuario_id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  FOREIGN KEY (rol_codigo) REFERENCES rol(codigo) ON DELETE RESTRICT
);

CREATE TABLE proveedor (
  codigo VARCHAR(40) NOT NULL,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  PRIMARY KEY (codigo)
);

CREATE TABLE consentimiento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  otorgado_en TIMESTAMPTZ NOT NULL,
  revocado_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  CHECK (revocado_en IS NULL OR revocado_en >= otorgado_en)
);

CREATE TABLE alcance (
  codigo VARCHAR(60) NOT NULL,
  descripcion VARCHAR(150) NOT NULL,
  PRIMARY KEY (codigo)
);

CREATE TABLE consentimiento_alcance (
  consentimiento_id BIGINT NOT NULL,
  alcance_codigo VARCHAR(60) NOT NULL,
  PRIMARY KEY (consentimiento_id, alcance_codigo),
  FOREIGN KEY (consentimiento_id) REFERENCES consentimiento(id) ON DELETE RESTRICT,
  FOREIGN KEY (alcance_codigo) REFERENCES alcance(codigo) ON DELETE RESTRICT
);

CREATE TABLE conexion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  consentimiento_id BIGINT NOT NULL UNIQUE,
  proveedor_codigo VARCHAR(40) NOT NULL,
  estado VARCHAR(12) NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL,
  revocada_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  FOREIGN KEY (consentimiento_id) REFERENCES consentimiento(id) ON DELETE RESTRICT,
  FOREIGN KEY (proveedor_codigo) REFERENCES proveedor(codigo) ON DELETE RESTRICT,
  CHECK (estado IN ('active','revoked'))
);

CREATE TABLE cuenta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  historial_desde DATE,
  historial_hasta DATE,
  confirmado_en TIMESTAMPTZ,
  confirmado_por BIGINT,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (confirmado_por) REFERENCES usuario(id) ON DELETE RESTRICT,
  CHECK (historial_desde IS NULL OR historial_hasta IS NULL OR historial_desde <= historial_hasta)
);

CREATE TABLE corte_cuenta (
  cuenta_id BIGINT NOT NULL,
  fecha DATE NOT NULL,
  saldo NUMERIC(18,2) NOT NULL,
  PRIMARY KEY (cuenta_id, fecha),
  FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE RESTRICT
);

CREATE TABLE tercero (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  nombre_normalizado VARCHAR(250) NOT NULL,
  nombre_visible VARCHAR(250) NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  UNIQUE (empresa_id,nombre_normalizado)
);

CREATE TABLE alias_tercero (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tercero_id BIGINT NOT NULL,
  proveedor_codigo VARCHAR(40) NOT NULL,
  alias_normalizado VARCHAR(250) NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (tercero_id) REFERENCES tercero(id) ON DELETE RESTRICT,
  FOREIGN KEY (proveedor_codigo) REFERENCES proveedor(codigo) ON DELETE RESTRICT,
  UNIQUE (tercero_id,proveedor_codigo,alias_normalizado)
);

CREATE TABLE categoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  PRIMARY KEY (id)
);

CREATE TABLE movimiento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  cuenta_id BIGINT NOT NULL,
  externo_id VARCHAR(120) NOT NULL,
  fecha DATE NOT NULL,
  importe NUMERIC(18,2) NOT NULL,
  descripcion VARCHAR(250) NOT NULL,
  descripcion_normalizada TEXT NOT NULL,
  tercero_id BIGINT,
  tercero_original VARCHAR(250) NOT NULL,
  categoria_id BIGINT NOT NULL,
  fuente_clasificacion VARCHAR(16) NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE RESTRICT,
  FOREIGN KEY (tercero_id) REFERENCES tercero(id) ON DELETE RESTRICT,
  FOREIGN KEY (categoria_id) REFERENCES categoria(id) ON DELETE RESTRICT,
  UNIQUE (cuenta_id,externo_id),
  CHECK (importe <> 0)
);

CREATE TABLE regla_clasificacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  descripcion_normalizada VARCHAR(250) NOT NULL,
  direccion VARCHAR(3) NOT NULL,
  categoria_id BIGINT NOT NULL,
  actualizada_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (categoria_id) REFERENCES categoria(id) ON DELETE RESTRICT,
  UNIQUE (empresa_id,descripcion_normalizada,direccion),
  CHECK (direccion IN ('in','out'))
);

CREATE TABLE cambio_clasificacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  movimiento_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  categoria_anterior_id BIGINT NOT NULL,
  categoria_nueva_id BIGINT NOT NULL,
  recordado BOOLEAN NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (movimiento_id) REFERENCES movimiento(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  FOREIGN KEY (categoria_anterior_id) REFERENCES categoria(id) ON DELETE RESTRICT,
  FOREIGN KEY (categoria_nueva_id) REFERENCES categoria(id) ON DELETE RESTRICT
);

CREATE TABLE importacion_movimiento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  cuenta_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  formato VARCHAR(4) NOT NULL,
  checksum CHAR(64) NOT NULL,
  contenido TEXT,
  estado VARCHAR(12) NOT NULL,
  creados INTEGER NOT NULL,
  duplicados INTEGER NOT NULL,
  error VARCHAR(300),
  creada_en TIMESTAMPTZ NOT NULL,
  finalizada_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  CHECK (formato IN ('csv','xlsx') AND creados >= 0 AND duplicados >= 0)
);

CREATE TABLE sincronizacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  conexion_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  estado VARCHAR(12) NOT NULL,
  creados INTEGER NOT NULL,
  duplicados INTEGER NOT NULL,
  error VARCHAR(300),
  creada_en TIMESTAMPTZ NOT NULL,
  finalizada_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  FOREIGN KEY (conexion_id) REFERENCES conexion(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  CHECK (creados >= 0 AND duplicados >= 0)
);

CREATE TABLE obligacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  referencia VARCHAR(120) NOT NULL,
  contraparte_original VARCHAR(200) NOT NULL,
  descripcion VARCHAR(200) NOT NULL,
  direccion VARCHAR(3) NOT NULL,
  vencimiento DATE NOT NULL,
  importe_base NUMERIC(18,2) NOT NULL,
  cancelada BOOLEAN NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  UNIQUE (empresa_id,referencia),
  CHECK (importe_base >= 0 AND direccion IN ('in','out'))
);

CREATE TABLE conciliacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  obligacion_id BIGINT NOT NULL,
  movimiento_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  importe NUMERIC(18,2) NOT NULL,
  solicitud_id UUID NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL,
  revertida_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  FOREIGN KEY (obligacion_id) REFERENCES obligacion(id) ON DELETE RESTRICT,
  FOREIGN KEY (movimiento_id) REFERENCES movimiento(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  UNIQUE (obligacion_id,solicitud_id),
  CHECK (importe > 0)
);

CREATE TABLE factura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  cufe VARCHAR(150) NOT NULL UNIQUE,
  numero VARCHAR(100) NOT NULL,
  emision DATE NOT NULL,
  vencimiento_xml DATE,
  subtotal NUMERIC(18,2) NOT NULL,
  total NUMERIC(18,2) NOT NULL,
  pagadero NUMERIC(18,2) NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  CHECK (subtotal >= 0 AND total >= 0 AND pagadero >= 0)
);

CREATE TABLE parte_factura (
  factura_id BIGINT NOT NULL,
  papel VARCHAR(8) NOT NULL,
  nit_declarado VARCHAR(30) NOT NULL,
  nombre_declarado VARCHAR(200) NOT NULL,
  PRIMARY KEY (factura_id, papel),
  FOREIGN KEY (factura_id) REFERENCES factura(id) ON DELETE RESTRICT,
  CHECK (papel IN ('emisor','receptor'))
);

CREATE TABLE importacion_factura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  contenido TEXT,
  estado VARCHAR(12) NOT NULL,
  error VARCHAR(300),
  creada_en TIMESTAMPTZ NOT NULL,
  finalizada_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT
);

CREATE TABLE revision_recurrencia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  huella CHAR(64) NOT NULL,
  estado VARCHAR(12) NOT NULL,
  usuario_id BIGINT NOT NULL,
  actualizada_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  UNIQUE (empresa_id,huella),
  CHECK (estado IN ('pending','confirmed','rejected'))
);

CREATE TABLE evidencia_recurrencia (
  revision_id BIGINT NOT NULL,
  movimiento_id BIGINT NOT NULL,
  fecha_observada DATE NOT NULL,
  importe_observado NUMERIC(18,2) NOT NULL,
  PRIMARY KEY (revision_id, movimiento_id),
  FOREIGN KEY (revision_id) REFERENCES revision_recurrencia(id) ON DELETE RESTRICT,
  FOREIGN KEY (movimiento_id) REFERENCES movimiento(id) ON DELETE RESTRICT
);

CREATE TABLE ocurrencia_recurrencia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  revision_id BIGINT NOT NULL,
  clave CHAR(64) NOT NULL,
  obligacion_id BIGINT NOT NULL UNIQUE,
  PRIMARY KEY (id),
  FOREIGN KEY (revision_id) REFERENCES revision_recurrencia(id) ON DELETE RESTRICT,
  FOREIGN KEY (obligacion_id) REFERENCES obligacion(id) ON DELETE RESTRICT,
  UNIQUE (revision_id,clave)
);

CREATE TABLE pronostico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  huella CHAR(64) NOT NULL,
  metodo VARCHAR(32) NOT NULL,
  horizonte SMALLINT NOT NULL,
  fecha_corte DATE NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  UNIQUE (empresa_id,huella),
  CHECK (horizonte BETWEEN 30 AND 90)
);

CREATE TABLE parametro_pronostico (
  pronostico_id BIGINT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  valor TEXT NOT NULL,
  PRIMARY KEY (pronostico_id, nombre),
  FOREIGN KEY (pronostico_id) REFERENCES pronostico(id) ON DELETE RESTRICT
);

CREATE TABLE punto_pronostico (
  pronostico_id BIGINT NOT NULL,
  fecha DATE NOT NULL,
  escenario VARCHAR(12) NOT NULL,
  saldo NUMERIC(18,2) NOT NULL,
  PRIMARY KEY (pronostico_id, fecha, escenario),
  FOREIGN KEY (pronostico_id) REFERENCES pronostico(id) ON DELETE RESTRICT,
  CHECK (escenario IN ('expected','lower','upper'))
);

CREATE TABLE entrada_cuenta (
  pronostico_id BIGINT NOT NULL,
  cuenta_id BIGINT NOT NULL,
  fecha_observada DATE NOT NULL,
  saldo_observado NUMERIC(18,2) NOT NULL,
  PRIMARY KEY (pronostico_id, cuenta_id),
  FOREIGN KEY (pronostico_id) REFERENCES pronostico(id) ON DELETE RESTRICT,
  FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE RESTRICT
);

CREATE TABLE entrada_movimiento (
  pronostico_id BIGINT NOT NULL,
  movimiento_id BIGINT NOT NULL,
  fecha_observada DATE NOT NULL,
  importe_observado NUMERIC(18,2) NOT NULL,
  categoria_observada_id BIGINT NOT NULL,
  PRIMARY KEY (pronostico_id, movimiento_id),
  FOREIGN KEY (pronostico_id) REFERENCES pronostico(id) ON DELETE RESTRICT,
  FOREIGN KEY (movimiento_id) REFERENCES movimiento(id) ON DELETE RESTRICT,
  FOREIGN KEY (categoria_observada_id) REFERENCES categoria(id) ON DELETE RESTRICT
);

CREATE TABLE entrada_obligacion (
  pronostico_id BIGINT NOT NULL,
  obligacion_id BIGINT NOT NULL,
  vencimiento_observado DATE NOT NULL,
  pendiente_observado NUMERIC(18,2) NOT NULL,
  direccion_observada VARCHAR(3) NOT NULL,
  PRIMARY KEY (pronostico_id, obligacion_id),
  FOREIGN KEY (pronostico_id) REFERENCES pronostico(id) ON DELETE RESTRICT,
  FOREIGN KEY (obligacion_id) REFERENCES obligacion(id) ON DELETE RESTRICT,
  CHECK (pendiente_observado >= 0 AND direccion_observada IN ('in','out'))
);

CREATE TABLE evaluacion_alerta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  pronostico_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  huella CHAR(64) NOT NULL,
  umbral_observado NUMERIC(18,2) NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (pronostico_id) REFERENCES pronostico(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  UNIQUE (pronostico_id,huella)
);

CREATE TABLE alerta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  evaluacion_id BIGINT NOT NULL,
  secuencia SMALLINT NOT NULL,
  nivel VARCHAR(12) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  saldo_minimo NUMERIC(18,2) NOT NULL,
  mensaje TEXT NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (evaluacion_id) REFERENCES evaluacion_alerta(id) ON DELETE RESTRICT,
  UNIQUE (evaluacion_id,secuencia),
  CHECK (fecha_inicio <= fecha_fin)
);

CREATE TABLE factor_alerta (
  alerta_id BIGINT NOT NULL,
  posicion SMALLINT NOT NULL,
  descripcion VARCHAR(250) NOT NULL,
  PRIMARY KEY (alerta_id, posicion),
  FOREIGN KEY (alerta_id) REFERENCES alerta(id) ON DELETE RESTRICT
);

CREATE TABLE auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  accion VARCHAR(80) NOT NULL,
  entidad VARCHAR(80) NOT NULL,
  objeto_id VARCHAR(80) NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE RESTRICT
);

CREATE TABLE detalle_auditoria (
  auditoria_id BIGINT NOT NULL,
  campo VARCHAR(120) NOT NULL,
  valor_anterior TEXT,
  valor_nuevo TEXT,
  PRIMARY KEY (auditoria_id, campo),
  FOREIGN KEY (auditoria_id) REFERENCES auditoria(id) ON DELETE RESTRICT
);

CREATE TABLE tarea (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  estado VARCHAR(12) NOT NULL,
  intentos SMALLINT NOT NULL,
  disponible_en TIMESTAMPTZ NOT NULL,
  lease UUID,
  creada_en TIMESTAMPTZ NOT NULL,
  finalizada_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  CHECK (intentos BETWEEN 0 AND 3)
);

CREATE TABLE parametro_tarea (
  tarea_id BIGINT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  valor TEXT NOT NULL,
  PRIMARY KEY (tarea_id, nombre),
  FOREIGN KEY (tarea_id) REFERENCES tarea(id) ON DELETE RESTRICT
);

CREATE TABLE limite_solicitud (
  clave CHAR(64) NOT NULL,
  solicitudes INTEGER NOT NULL,
  vence_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (clave),
  CHECK (solicitudes >= 0)
);

CREATE TABLE registro_factura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  empresa_id BIGINT NOT NULL,
  factura_id BIGINT NOT NULL,
  registrada_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (empresa_id) REFERENCES empresa(id) ON DELETE RESTRICT,
  FOREIGN KEY (factura_id) REFERENCES factura(id) ON DELETE RESTRICT,
  UNIQUE (empresa_id,factura_id)
);

CREATE TABLE cuenta_conexion (
  cuenta_id BIGINT NOT NULL,
  conexion_id BIGINT NOT NULL UNIQUE,
  PRIMARY KEY (cuenta_id),
  FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE RESTRICT,
  FOREIGN KEY (conexion_id) REFERENCES conexion(id) ON DELETE RESTRICT
);

CREATE TABLE factura_obligacion (
  registro_id BIGINT NOT NULL,
  obligacion_id BIGINT NOT NULL UNIQUE,
  PRIMARY KEY (registro_id),
  FOREIGN KEY (registro_id) REFERENCES registro_factura(id) ON DELETE RESTRICT,
  FOREIGN KEY (obligacion_id) REFERENCES obligacion(id) ON DELETE RESTRICT
);

CREATE TABLE resultado_importacion_factura (
  importacion_id BIGINT NOT NULL,
  registro_id BIGINT NOT NULL,
  duplicada BOOLEAN NOT NULL,
  PRIMARY KEY (importacion_id),
  FOREIGN KEY (importacion_id) REFERENCES importacion_factura(id) ON DELETE RESTRICT,
  FOREIGN KEY (registro_id) REFERENCES registro_factura(id) ON DELETE RESTRICT
);

CREATE INDEX ix_movimiento_cuenta_fecha ON movimiento(cuenta_id, fecha);

CREATE INDEX ix_obligacion_empresa_fecha ON obligacion(empresa_id, vencimiento);

CREATE INDEX ix_corte_cuenta_fecha ON corte_cuenta(cuenta_id, fecha DESC);

CREATE INDEX ix_pronostico_empresa_fecha ON pronostico(empresa_id, fecha_corte);

